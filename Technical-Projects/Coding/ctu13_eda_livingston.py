#Curated Feature Extraction & Train-Test Split
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import RobustScaler

# 1. Define the curated 12-feature analytical subset
selected_features = [
    'Flow IAT Min',       # Inter-arrival time minimum (Top tree discriminator)
    'Init Bwd Win Byts',  # TCP handshake initial window bytes
    'Pkt Len Std',        # Packet length standard deviation (Uniform vs. diverse payloads)
    'Pkt Len Mean',       # Packet length mean
    'SYN Flag Cnt',       # TCP SYN flag rate (Port sweeps / half-open scans)
    'FIN Flag Cnt',       # TCP FIN flag rate (Premature teardowns)
    'Bwd IAT Min',        # Backward inter-arrival time minimum
    'TotLen Bwd Pkts',    # Total backward payload bytes (Asymmetry marker)
    'Tot Bwd Pkts',       # Total backward packet count
    'Flow Duration',      # Session duration
    'Flow Byts/s',        # Throughput rate
    'Active Min'          # Minimum active session duration
]

X = df[selected_features]
y = df['Label']

# 2. Stratified 75/25 split preserving class proportions
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

print(f"Features Selected:   {len(selected_features)}")
print(f"Training Set Shape:  {X_train.shape[0]:,} samples")
print(f"Testing Set Shape:   {X_test.shape[0]:,} samples")

#Normalization Pipeline (RobustScaler)
# 3. Fit RobustScaler strictly on the training partition to prevent data leakage
scaler = RobustScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

print("RobustScaler successfully fitted across training distributions.")
print(f"Scaled feature matrix shape: {X_train_scaled.shape}")

#Supervised Modeling (Random Forest & Gradient Boosting)
from sklearn.ensemble import RandomForestClassifier, HistGradientBoostingClassifier
from sklearn.metrics import classification_report, roc_auc_score, confusion_matrix

# Model 1: Random Forest Classifier (Supervised Baseline)
rf_model = RandomForestClassifier(n_estimators=100, max_depth=15, random_state=42, n_jobs=-1)
rf_model.fit(X_train_scaled, y_train)

y_pred_rf = rf_model.predict(X_test_scaled)
y_prob_rf = rf_model.predict_proba(X_test_scaled)[:, 1]

# Model 2: HistGradientBoosting (LightGBM equivalent for rapid inference)
hgb_model = HistGradientBoostingClassifier(random_state=42, max_iter=100)
hgb_model.fit(X_train_scaled, y_train)

y_pred_hgb = hgb_model.predict(X_test_scaled)
y_prob_hgb = hgb_model.predict_proba(X_test_scaled)[:, 1]

print("=== Supervised Random Forest Performance ===")
print(classification_report(y_test, y_pred_rf, digits=4))
print(f"ROC-AUC Score: {roc_auc_score(y_test, y_prob_rf):.4f}")
print("Confusion Matrix:")
print(confusion_matrix(y_test, y_pred_rf))

#Unsupervised Anomaly Detection (Isolation Forest)
from sklearn.ensemble import IsolationForest

# Train Isolation Forest purely on Normal traffic to model zero-day deviations
iso_forest = IsolationForest(contamination=0.05, random_state=42, n_jobs=-1)
iso_forest.fit(X_train_scaled[y_train == 0])

# -1 represents anomaly (attack); 1 represents inlier (normal)
y_pred_iso_raw = iso_forest.predict(X_test_scaled)
y_pred_iso = np.where(y_pred_iso_raw == -1, 1, 0)

print("=== Unsupervised Isolation Forest Performance ===")
print(classification_report(y_test, y_pred_iso, digits=4))

